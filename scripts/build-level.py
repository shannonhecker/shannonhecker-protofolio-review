# Builds src/game/level.ts. Four beats after Hayashida (introduce, develop,
# twist) plus a short finish run, sized for ~45 s at a first-time player's pace.
# Rows: 0 top .. 16 bottom. Ground surface is row 14; items sit on row 13.
W, H = 176, 17
g = [[' '] * W for _ in range(H)]
def put(x, y, c): g[y][x] = c
def ground(x0, x1, top=14):
    for x in range(x0, x1):
        for y in range(top, H): put(x, y, '#')
def plat(x0, x1, y, c='='):
    for x in range(x0, x1): put(x, y, c)
def dots(xs, y):
    for x in xs: put(x, y, 'o')

# Beat 1: introduce (cols 0-37). Flat, one 2-wide gap, dots arc over it.
ground(0, 16); ground(18, 38)
put(2, 13, 'P')
dots([6, 9], 13); dots([16, 17], 11)
plat(24, 28, 11); dots([25, 27], 10)
# Beat 2: develop (cols 38-89). Gaps widen 2 -> 3 -> 4, hazards between.
put(38, 13, 'C')
ground(38, 52); ground(55, 66); ground(70, 82); ground(86, 96)
dots([53], 11); dots([67, 68], 11); dots([83, 84], 10)
put(46, 13, '^'); put(60, 13, '^'); put(61, 13, '^'); put(76, 13, '^')
plat(58, 62, 10); dots([59, 61], 9)
plat(74, 78, 10); dots([75, 77], 9)
# Beat 3: twist (cols 90-147). Climb a staircase of solid steps, then cross a
# long pit on floating islands and come back down.
put(90, 13, 'C')
for i, x in enumerate(range(96, 112, 4)):
    ground(x, x + 4, top=13 - i * 2)
    dots([x + 2], 12 - i * 2)
put(110, 6, 'C')  # top of the stairs: a fall in the pit costs seconds, not the climb
# islands over the pit (solid tops at decreasing heights)
for x, top in [(115, 9), (120, 10), (125, 11), (130, 12)]:
    for xx in range(x, x + 3): put(xx, top, '#')
    put(x + 1, top - 1, 'o')
ground(135, 148)
put(140, 13, '^')
# Beat 4: conclude (cols 148-175). Flat run, a line of dots, finish.
put(148, 13, 'C')
ground(148, 176)
dots(range(152, 168, 3), 13)
put(172, 13, 'F')

rows = [''.join(r) for r in g]
total_dots = sum(r.count('o') for r in rows)
hdr = """// Generated by scripts/build-level.py. Edit that, not this.
// Four beats: introduce (0-37), develop (38-89), twist (90-147), conclude (148-175).
// Legend: # solid, = one-way, o collectible, ^ hazard, P spawn, C checkpoint, F finish.
"""
body = 'export const LEVEL = [\n' + '\n'.join(f"  '{r}'," for r in rows) + '\n];\n'
src = open('src/game/level.ts').read()
tail = src[src.index('export type Tile'):]
open('src/game/level.ts', 'w').write(hdr + '\n' + body + '\n' + tail)
print('cols', W, 'px', W * 32, 'dots', total_dots)
for r in rows: print(r)
